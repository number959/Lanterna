// CodeText dà "0x000000D1 DRIVER_IRQL_NOT_LESS_OR_EQUAL", o solo il codice
// se non è nell'elenco.
func CodeText(code uint32) string {
	if n, ok := Names[code]; ok {
		return fmt.Sprintf("0x%08X %s", code, n)
	}
	return fmt.Sprintf("0x%08X", code)
}
