// Catalogo delle azioni correttive. Più problemi possono puntare alla stessa
// azione: il piano d'azione le unisce, così l'utente vede "Sposta il router"
// una volta sola anche se migliora segnale, velocità e stabilità insieme.
//
// Passi guidati. Dove un passo si fa in Windows, text segue Windows 11 e
// win10 il percorso di Windows 10, quando è diverso. I nomi di menu e pulsanti
// stanno tra virgolette solo se due fonti indipendenti li confermano (ricerca
// dell'8/11/2026 su guide italiane e pagine dei produttori di PC; le pagine
// italiane di Microsoft sono in parte tradotte automaticamente e da sole non
// bastano). Le voci non confermate sono descritte senza virgolette. open apre
// una pagina della lista bianca (WINDOWS_TOOLS in tools.ts, o il pannello del
// router); cmd è un comando da copiare, che Polaris non esegue mai; {driver}
// nel comando diventa il driver ricorrente nelle schermate blu (stepCmd).

/** Il pannello del router: lo stesso identificativo di ROUTER_PANEL in tools.ts (lo controlla il test dei passi). */
const ROUTER = 'router-panel';
/** Primo passo nel pannello del router, con il pulsante che lo apre. */
const router = (text: string): ActionStep => ({ text, where: 'router', open: ROUTER });
/** Passo successivo, sempre nel pannello del router. */
const onRouter = (text: string): ActionStep => ({ text, where: 'router' });
/** Passo da fare su un altro dispositivo. */
const onDevice = (text: string): ActionStep => ({ text, where: 'device' });

